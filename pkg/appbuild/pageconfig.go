package appbuild

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/irgipaulius/cogs/pkg/fileutil"
	"github.com/irgipaulius/cogs/pkg/launch"
)

// WritePageConfig writes production UI config into pages-dist (not tracked public/).
func WritePageConfig(appDir, pageHost, apiHost string, m launch.Manifest) error {
	dir := PagesDistDir(appDir)
	path := filepath.Join(dir, "config.js")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	extra := ""
	if strings.Contains(m.Name, "todo") {
		extra = "  localKey: \"cogs_todo_v1\",\n  offlineQueueKey: \"cogs_todo_offline_v1\",\n"
	}
	body := fmt.Sprintf(`// Generated by CoGS — do not hand-edit.
window.COGS_CONFIG = {
  pageOrigin: "https://%s",
  apiBase: "https://%s",
%s};
`, pageHost, apiHost, extra)
	return fileutil.WriteFileIfChanged(path, []byte(body), 0o644)
}
